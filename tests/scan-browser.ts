import { chromium } from "playwright";
import express from "express";
import assert from "node:assert/strict";
import { memDb } from "./helpers.js";
import { initializeHosted } from "../src/hosted-runtime.js";
import { createHostedApp } from "../src/hosted-app.js";
import { passwordHash } from "../src/auth.js";

delete process.env.PUBLIC_BASE_URL;
delete process.env.VERCEL;
delete process.env.GOOGLE_SERVICE_ACCOUNT_FILE;
delete process.env.GOOGLE_SERVICE_ACCOUNT_JSON;
const db = await memDb();
await initializeHosted(db);
await db.query("INSERT INTO coffee.staff_accounts VALUES($1,$2,$3,true)", ["scanner", passwordHash("browser-scanner-password"), "staff"]);
const member = (await db.query("SELECT coffee.enroll_customer('Scan customer') AS member")).rows[0].member;
const app = createHostedApp(db);
// Simulate repeated decoded frames, not a physical camera. The real API/database handle the purchase.
app.get("/vendor/zxing/zxing-browser.min.js", (_req, res) => res.type("js").send(`
window.ZXingBrowser={BrowserQRCodeReader:class {
 async decodeFromVideoDevice(id,video,callback){
  const controls={stop(){}};
  window.scanTestFrame=()=>{const result={getText:()=>window.scanTestId};callback(result,null,controls);callback(result,null,controls);};
  return controls;
 }
}};`));
app.use(express.static("public"));
const server = app.listen(0, "127.0.0.1");
await new Promise<void>(resolve => server.once("listening", resolve));
const origin = `http://127.0.0.1:${(server.address() as {port: number}).port}`;
let browser;
try {
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH });
  const page = await browser.newPage();
  let lastLoginToken: string;
  await page.route("**/api/login", async route => {
    const response = await route.fetch();
    const data = await response.json();
    if (response.ok()) lastLoginToken = data.token;
    await route.fulfill({ response });
  });
  let dialogs = 0;
  const errors: string[] = [];
  page.on("dialog", dialog => { dialogs++; void dialog.accept(); });
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(origin + "/business/login.html");
  await page.locator("#username").fill("scanner");
  await page.locator("#password").fill("browser-scanner-password");
  await page.locator("#login button").click();
  await page.waitForURL("**/business/dashboard.html*");
  const scan = async (scanId = member.id) => {
    await page.locator("#tab-scan").click();
    await page.locator("#scan").click();
    await page.evaluate(id => {
      const test = window as unknown as {scanTestId: string; scanTestFrame: () => void};
      test.scanTestId = id;
      test.scanTestFrame();
    }, scanId);
    await page.waitForFunction(() => !(document.querySelector("#scan") as HTMLButtonElement).disabled);
    if ((await page.locator("#message").textContent())?.startsWith("Card identified")) await page.locator("#purchase").click();
  };
  assert.equal(await page.locator("#purchase").count(), 1);
  await scan("https://example.com/not-a-customer-card");
  await page.getByText("Invalid QR code. Please show a valid customer membership QR for Demo Coffee Shop.", { exact: true }).first().waitFor();
  assert.equal(Number((await db.query("SELECT stamps FROM coffee.members WHERE id=$1", [member.id])).rows[0].stamps), 0);
  await scan();
  await page.waitForFunction(() => document.querySelector("#customer-outcome")?.textContent?.startsWith("One stamp added"));
  assert.equal(Number((await db.query("SELECT stamps FROM coffee.members WHERE id=$1", [member.id])).rows[0].stamps), 1);
  await scan();
  await page.waitForFunction(() => document.querySelector("#customer-outcome")?.textContent?.includes("No extra stamp"));
  assert.equal(Number((await db.query("SELECT stamps FROM coffee.members WHERE id=$1", [member.id])).rows[0].stamps), 1);
  await db.query("UPDATE coffee.scan_requests SET created_at=created_at-6000");
  let loseResponse = true;
  await page.route("**/api/staff/members/*/scan", async route => {
    if (loseResponse) { loseResponse = false; await route.fetch(); await route.abort("failed"); }
    else await route.continue();
  });
  await scan();
  await page.waitForFunction(() => document.querySelector("#customer-outcome")?.textContent?.includes("request key is retained"));
  await page.reload();
  await page.locator("#identity").filter({hasText:"scanner"}).waitFor();
  await scan();
  await page.waitForFunction(() => document.querySelector("#customer-outcome")?.textContent?.startsWith("One stamp added"));
  assert.equal(Number((await db.query("SELECT stamps FROM coffee.members WHERE id=$1", [member.id])).rows[0].stamps), 2);
  assert.equal(await page.evaluate(() => sessionStorage.getItem("coffeePending")), null);
  await page.locator("#logout").click();
  await page.waitForURL("**/business/login.html");
  await page.goto(origin + "/business/register.html");
  for (const [name, value] of Object.entries({ shopName: "Browser Roasters", fullName: "Browser Owner", username: "browser-owner", password: "browser-owner-password", confirmPassword: "browser-owner-password" }))
    await page.locator(`[name=${name}]`).fill(value);
  await page.locator("#register button").click();
  await page.waitForURL("**/business/login.html?*");
  await page.locator("#password").fill("browser-owner-password");
  await page.locator("#login button").click();
  await page.waitForURL("**/business/dashboard.html*");
  await scan(member.id);
  await page.getByText("Invalid QR code. Please show a valid customer membership QR for Browser Roasters.", { exact: true }).first().waitFor();
  assert.equal(Number((await db.query("SELECT stamps FROM coffee.members WHERE id=$1", [member.id])).rows[0].stamps), 2);
  await page.locator("#tab-design").click();
  await page.locator("#shop-branding").waitFor({ state: "visible" });
  const me = await (await page.request.get(origin + "/api/staff/me", { headers: { Authorization: "Bearer " + lastLoginToken! } })).json();
  assert.notEqual(me.shopId, "default");
  assert.equal(await page.locator("#shop-qr-link").getAttribute("href"), "/shop.html?shop=" + me.shopId);
  await page.locator("#card-title").fill("Regulars club");
  await page.locator("#card-tagline").fill("Thanks for being a regular.");
  await page.locator("#reward-label").fill("Free latte");
  await page.locator("#shop-color").fill("#eedd99");
  await page.locator("#stamp-icon").selectOption("heart");
  await page.locator("#card-style").selectOption("minimal");
  await page.locator("#shop-logo").setInputFiles("public/icons/icon-192.png");
  await page.waitForFunction(() => document.querySelector("#design-message")?.textContent?.includes("Logo ready"));
  await page.locator("#save-design").click();
  await page.waitForFunction(() => document.querySelector("#design-message")?.textContent?.startsWith("Published"));
  assert.equal(await page.locator("#card-preview .card-logo").count(), 1);
  assert.equal(await page.locator("#enroll").count(), 0);
  await page.locator("#tab-referrals").click();
  await page.locator("#referral-amount").fill("2");
  await page.locator("#referral-settings button").click();
  await page.getByText("Saved. New referred signups will use these settings.").waitFor();
  const customer = await browser.newContext();
  const card = await customer.newPage();
  card.on("pageerror", error => { errors.push(error.message); console.error("Customer page error:",error.message); });
  await card.goto(origin + "/join.html?shop=" + me.shopId);
  await card.locator("#name").fill("New shop customer");
  await card.locator("#accept").check();
  await card.locator("#submit").click();
  await card.waitForURL(url => url.searchParams.has("member"));
  await card.waitForFunction(() => document.querySelector("nav a")?.textContent === "Browser Roasters");
  assert.equal(await card.locator("#card-progress").textContent(), "0 / 8 stamps");
  assert.equal(await card.locator("#card .card-logo").count(), 1);
  assert.equal(await card.locator("#card .card-label").textContent(), "Browser RoastersRegulars club");
  assert.ok((await card.locator("#card-rewards").textContent())?.includes("Free latte"));
  const invitation = await card.locator("#referral-link").inputValue();
  assert.ok(!invitation.includes(new URL(card.url()).searchParams.get("member")!));
  const friendContext = await browser.newContext();
  const friend = await friendContext.newPage();
  await friend.goto(invitation);
  await friend.getByText("You’ve been invited!", { exact: false }).waitFor();
  await friend.locator("#name").fill("Referred friend");
  await friend.locator("#accept").check();
  await friend.locator("#submit").click();
  await friend.waitForURL(url => url.searchParams.has("member"));
  await friend.locator("#card-progress").waitFor();
  await scan(new URL(friend.url()).searchParams.get("member")!);
  await page.waitForFunction(() => document.querySelector("#customer-outcome")?.textContent?.startsWith("One stamp added"));
  await card.bringToFront();
  await card.evaluate(()=>window.dispatchEvent(new Event("online")));
  await card.waitForFunction(() => document.querySelector("#card-progress")?.textContent === "2 / 8 stamps", {}, { timeout: 12000 });
  await card.getByText("1 joined · 1 qualified · 0 awaiting a first purchase").waitFor();
  await page.locator("#tab-overview").click();
  await page.waitForFunction(() => document.querySelector("#shop-metrics .metric strong")?.textContent === "2");
  assert.equal(await page.locator("#shop-metrics .metric").first().locator("strong").textContent(), "2");
  await page.locator("#tab-referrals").click();
  await page.getByText("New shop customer → Referred friend").waitFor();
  await friendContext.close();
  await card.goto(origin + "/join.html?shop=default");
  await card.locator("#name").fill("Same customer, other shop");
  await card.locator("#accept").check();
  await card.locator("#submit").click();
  await card.waitForURL(url => url.searchParams.has("member"));
  await card.locator("#card-progress").waitFor();
  await card.goto(origin + "/");
  await card.locator(".wallet-card").nth(1).waitFor();
  assert.equal(await card.locator(".wallet-card").count(), 2);
  assert.ok((await card.locator("#card").textContent())?.includes("Browser Roasters"));
  await card.locator("#add-card").click();
  await card.locator("#card-url").fill("https://evil.example/join.html?shop=default");
  await card.locator("#add-card-form button").click();
  await card.getByText("Use a card or shop link from this loyalty app.").waitFor();
  await card.locator("#close-add-card").click();
  await card.locator(".wallet-card").first().click();
  await card.locator("#card-progress").waitFor();
  assert.equal(await page.evaluate(() => sessionStorage.getItem("loyalty-staff-handoff")), null);
  await page.reload();
  await page.locator("#identity").filter({hasText:"browser-owner"}).waitFor();
  await page.goto(origin + "/business/dashboard.html");
  await page.locator("#identity").filter({hasText:"browser-owner"}).waitFor();
  await customer.close();
  assert.ok(dialogs > 0);
  assert.deepEqual(errors, []);
  console.log("Browser flows passed: invalid/wrong-shop QR rejection, confirmed stamping and retry safety, refresh-safe staff sessions, owner card design with logo, referral sharing/first-purchase rewards, dashboard monitoring, and a two-shop customer wallet. Purchase confirmations and no browser exceptions.");
} finally {
  await browser?.close();
  await new Promise<void>(resolve => server.close(() => resolve()));
  await db.end();
}
